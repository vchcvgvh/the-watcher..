package com.thewatcher.gen;

/** Every block the realms are built from (with the block-state variants they need). Mapped to real blocks in-game. */
public enum B {
    AIR, STONE, BEDROCK, WATER,
    // Hallways
    YELLOW_TERRACOTTA, WHITE_TERRACOTTA, SMOOTH_SANDSTONE, SEA_LANTERN, REDSTONE_LAMP, BROWN_TERRACOTTA, RED_TERRACOTTA,
    BROWN_CARPET, IRON_BARS, CHAIR_N, CHAIR_E, CHAIR_S, CHAIR_W, DOOR_LOWER, DOOR_UPPER, COBWEB,
    // shared markers
    CRYING_OBSIDIAN, SHROOMLIGHT,
    // Hollow
    DIRT, COARSE_DIRT, ROOTED_DIRT, DEEPSLATE, DARK_OAK_LOG, DARK_OAK_LOG_X, DARK_OAK_LOG_Z, DEAD_BUSH, BONE_BLOCK,
    SKELETON_SKULL, COBBLED_DEEPSLATE_WALL, SOUL_LANTERN, SOUL_LANTERN_HANGING, POLISHED_BLACKSTONE_BRICKS, CHAIN,
    STONE_BRICK_WALL, DEEPSLATE_BRICKS, CRACKED_DEEPSLATE_BRICKS, BROWN_MUSHROOM,
    // Flesh
    NETHER_WART_BLOCK, RED_MUSHROOM_BLOCK, CRIMSON_HYPHAE, MAGMA_BLOCK, PEARLESCENT_FROGLIGHT, BONE_BLOCK_X, BONE_BLOCK_Z,
    DRIP_DOWN_TIP, DRIP_DOWN_FRUSTUM, DRIP_DOWN_BASE, DRIP_UP_TIP, DRIP_UP_FRUSTUM, DRIP_UP_BASE,
    // Still Water
    MUD, MANGROVE_LOG, MANGROVE_ROOTS_WET, STONE_BRICKS, MOSSY_STONE_BRICKS, CRACKED_STONE_BRICKS, MOSSY_COBBLESTONE,
    LILY_PAD, SEAGRASS, SPRUCE_FENCE, SPRUCE_FENCE_WET, LANTERN, LANTERN_HANGING;

    public boolean isLight() {
        return this == SEA_LANTERN || this == SHROOMLIGHT || this == SOUL_LANTERN || this == SOUL_LANTERN_HANGING
                || this == CRYING_OBSIDIAN || this == MAGMA_BLOCK || this == PEARLESCENT_FROGLIGHT
                || this == LANTERN || this == LANTERN_HANGING;
    }
}
